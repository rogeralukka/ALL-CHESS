"""Packs the loader frames into one WebP sprite sheet (12 columns) for LoadingScreen, and writes
src/components/loaderSheet.ts with the sheet geometry (frame size, gutter, where the floor is).

Run:  python pack_loader.py <frames_dir> <out.webp> [frame_height]

The frames have no baked shadow (render_loader.py renders without a shadow catcher): the UI draws
a soft shadow under the piece, so nothing can be clipped into a square edge by the crop.
Frames sit in cells with a transparent gutter so scaled sprites never show a sliver of the next frame.
"""
import glob
import os
import sys

from PIL import Image

src, out = sys.argv[1], sys.argv[2]
H = int(sys.argv[3]) if len(sys.argv) > 3 else 320
COLS, GAP = 12, 4
frames = sorted(glob.glob(os.path.join(src, 'f*.png')))

# crop every frame to the union of their visible pixels, so the piece fills the sprite
box = None
for f in frames:
    b = Image.open(f).getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
    if b:
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
pad = 8
box = (box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad)
bw, bh = box[2] - box[0], box[3] - box[1]
W = round(H * bw / bh)
k = H / bh
print('crop', box, '->', W, 'x', H)

# the floor: bottom of the standing piece in the first frame, and its centre
b0 = Image.open(frames[0]).getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox()
ground_y = (b0[3] - box[1]) * k
ground_x = ((b0[0] + b0[2]) / 2 - box[0]) * k
base_w = (b0[2] - b0[0]) * k

rows = (len(frames) + COLS - 1) // COLS
SW, SH = COLS * (W + GAP), rows * (H + GAP)
sheet = Image.new('RGBA', (SW, SH), (0, 0, 0, 0))
for i, f in enumerate(frames):
    im = Image.open(f).convert('RGBA').crop(box).resize((W, H), Image.LANCZOS)
    sheet.paste(im, ((i % COLS) * (W + GAP), (i // COLS) * (H + GAP)))
sheet.save(out, 'WEBP', quality=84, alpha_quality=90, method=6)
print(len(frames), 'frames ->', out, sheet.size, os.path.getsize(out) // 1024, 'KB')

ts = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'components', 'loaderSheet.ts')
with open(ts, 'w', encoding='utf-8') as fh:
    fh.write(
        '// Generated by scripts/map-art/pack_loader.py. Do not edit by hand.\n'
        '/** Geometry of /assets/ui/loader_sheet.webp: frames are FW x FH cells separated by GAP px. */\n'
        f'export const LOADER_SHEET = {{\n'
        f'  cols: {COLS},\n  frames: {len(frames)},\n  fw: {W},\n  fh: {H},\n  gap: {GAP},\n'
        f'  sheetW: {SW},\n  sheetH: {SH},\n'
        f'  /** where the standing piece meets the floor, in frame pixels */\n'
        f'  groundX: {ground_x:.1f},\n  groundY: {ground_y:.1f},\n'
        f'  /** width of the standing piece\'s base, in frame pixels */\n'
        f'  baseW: {base_w:.1f},\n'
        '} as const;\n'
    )
print('wrote', os.path.normpath(ts))
